// 1.是什么环境变量
// 环境变量：一般指在操作系统中指定系统运行环境的一些参数（在系统中通常具有全局属性）
// 从储存的角度理解环境变量：
// 是在shell(bash)中储存的一张表
// 那表中数据哪来的？
// 系统相关的配置文件中来的
// 
// 1.1命令行参数
// main函数的参数：(父进程传的)
// int main(int argc, char* argv[], char* env[])
// argc：命令行参数的个数
// argv[]：命令行参数列表（支持选项功能）
// env[]：环境变量表
// 
// 结论：main的命令行参数，是实现程序不同子功能的方法（也就是指令选项的原理）
// 
// 
// 2.一个环境变量 + 一个例子 
// PATH
// 例子：
// 环境变量PATH中记录系统指令文件的路径，帮助我们不带路径运行系统指令（程序）
// 所以执行指令时，bash通过PATH环境变量来找指令文件
// 
// 
// 3.更多的环境变量（用指令env查询，格式：名称=内容）
// 环境变量生命周期：内存、文件
// 
// HOME    家目录
// SHELL   哪个版本的
// USER    
// LOGNAME 
//    su -
// HSITSIZE
// HOSTNAME
// PWD
// OLDPWD
// 
// 
// 4.获取环境变量的办法（环境变量相关命令）
// 4.1 操作
// env
// echo $XXX
// export XXX=
// unset XXX
// set
// 
// 
// 5.理解环境变量的特性
// 5.1 环境变量具有全局属性，可被子进程继承
// 
// 5.2 补充
// a.除了环境变量，还有一个本地变量，不会被子进程继承，只能在当前bash内使用
// b.内建命令：不需要创建子进程，bash自己执行（自己调用函数或者系统调用）
