// 
// 文件系统的基本功能：把文件储存到磁盘中，且能让我们找到（能读能写）
// 
// 
// 磁盘的物理结构（电脑中唯一的机械设备）
// 面：扇区、磁线（围成一个圈）、磁头...
// 体：柱面、传动臂（所有磁头共进退）...
// 
// 物理上如何找到一块内存？
// 需要三个参数：柱面(Cylind) 磁头(Head) 扇区(Sector) -> CHS定址
// 
// 
// 可以对磁盘的结构进行逻辑上的抽象，抽象为一维数组
// 把磁线拉直就是一个一维数组，基本储存单位：扇区（512B）
// （所以如果我们想修改一个扇区的一个bit位，就要把一整个扇区读入内存，修改后再拷回来）
// 一个面由一圈圈磁线构成的同心圆组成，全部拉直就是一个二维数组
// 磁盘是一个立体结构（有多片，每片两面），每面结合就是一个三维数组
// 但是任何多维数组最终都可看做由多个一维数组构成
// 
// 文件系统如何找到一块内存？（相当于找数组下标）
// 所需参数：
// 
// CHS 与 LBA 可以互相转化
// 
// 磁盘是一种块设备，不以字节为单位读取（以块为单位），支持随机读取
// 块的大小：4KB（八个扇区）
// 文件系统使用磁盘块，也是以4KB为单位的
// （磁盘迁就文件系统，磁盘上的数据块天然为了随时载入内存而准备）
// ps.块设备相对的是字符设备：键盘、显示器（不支持随机读取）
// 
// 文件系统的分区（文件系统的载体是分区，故每个分区的文件系统可能不一样）
// 一块大内存分为几个区
// 一个区分为若干个同样大小的块组(Block Group)
// 块组中有哪些划分：
// Super Block：保存了整个分区的使用情况，部分块组才有（内容是一样的），用于数据恢复（作用就是备份）
// GDT：保存了该块组的描述信息（划分块区域），一个块组一个
// inode Table：保存了文件的属性（不包括文件名，所以大小能固定128字节）
// inode Bitmap：位图，记录inode Table的使用情况，看哪个已被占用
// Data Block：保存文件的内容
// Data Bitmap：位图，记录Data Block的使用情况，看哪个已被占用
// （所以删除数据就只用把对应的Bitmap都置为0）
// 
// 
// inode中含有文件的编号，用于找到文件（ls -il）
// 编号可以跨组，不能跨分区（也就是同一组中编号唯一）
// 文件可以跨组保存（计算一个组的储存大小）
// 
// 
// 目录(文件夹)是什么东西
// 在文件系统看来与普通文件无异，但目录的数据储存的是文件名称，
// 从而建立文件名与编号的映射关系，也就可以通过路径+文件名找到该文件的inode，进而找到文件数据
// 所以在Linux中找任何文件，都必须从/目录开始，进行路径解析，直到找到对应文件
// /root/test/code.c
// 首先我们要知道文件路径，由系统提供/目录的inode，一个个目录建立映射关系，最后找到文件的inode
// 
// 不是访问所有文件都要进行路径解析，这样效率太低了，
// OS会把历史访问的路径记录下来，形成一颗多叉树(dentry),树中存有该文件/目录的inode
// 
// 
// 软链接（Windows中的快捷方式）
// 拥有独立的inode，数据块中储存链接文件的路径
// 
// 硬链接（用于备份数据）
// 本质不是独立文件，没有独立inode，共享inode，
// 链接时引用计数++就行了，就是建立一组新的文件名与目标inode的映射关系
// 平常的隐藏文件 . 和 .. 就是硬链接，所以一个目录的引用计数至少是2
