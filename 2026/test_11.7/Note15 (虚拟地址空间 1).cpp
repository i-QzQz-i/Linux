// 
//		1.引入概念
// 
// 进程地址空间(虚拟地址空间)（不是真正的内存地址）（会讲4次）
// 是一个系统的概念，而不是语言层的概念
// 
//	                 进程地址空间                                                                  内存
// 高地址      |---------------------| ------                                         ------- |------------|
//   ↑        |       内核空间	     |        |                                      |		  |			   |
//             |         (1G)		 |		  |									     |		  |			   |
//             |---------------------|		  |									     |		  |			   |
//             |					 |		  |									     |		  |			   |
//             | 命令行参数/环境变量 | 	      |									     |		  |			   |
//             |					 |		  |									     |		  |			   |
//   4G	       |         栈↓	     |		  |									     |		  |			   |
//  (32位	   |					 |		  |									     |		  |			   |
//  系统)      |        共享区       |		  |									     |		  |			   |
//             |  (一大段镂空的空间) |		  |									     |		  |			   |
//             |					 |		  |									     |		  |------------|
//             |         堆↑		 |		  | --→|---------页表---------|权-限|-→|		  
//             |					 |				| 虚拟地址	| 物理地址 |r-w-x|		  
//             |     未初始化数据	 |				|-----------|----------|-----|		  
//             |      初始化数据     |			    |			|	       |	 |		  
//             |       正文代码	     |				|-----------|----------|-----|		  
//             |		             |				|			|	       |	 |		  
// 	  ↓	   |         (3G)        | 			    |-----------|----------|-----|		  
//  低地址     |---------------------|								 					 
//  
// 32位机器 - 2^32个地址（一个地址表示一个字节）
// 
//
// 
// 1.1 一个进程，一个虚拟地址空间（让每个程序认为自己都有4G的空间）
// 1.2 一个进程，一套列表
// 1.3 页表用于做虚拟地址和物理地址的映射（把虚拟地址给用户层使用）
// 
// fork时父进程的虚拟地址空间和页表，直接拷贝给子进程
// 如果父子进程的值需要修改时，进行写时拷贝
// （新开一份物理空间给修改的数据，并修改页表的物理地址，但虚拟地址不变）
// 
// 为什么要写时拷贝（写时拷贝的好处）
// 1.减少创建的时间
// 2.减少内存消耗
// 
//		2.程序实现过程
// （1）在虚拟地址空间中申请大小的空间
// （虚拟地址空间的划分，只需要记录该段空间的开始与结束）
// （2）加载程序，申请物理空间
// （3）页表映射虚拟与物理空间
// 
// 
//		3.为什么要有虚拟地址（为什么不让我们直接访问物理地址空间）
// （1）让地址空间从“无序”变为“有序”
// （程序在物理内存，理论上可以任意位置加载）
// （2）保护物理内存
// （虚拟地址空间与页表是OS创建并维护，可以地址(野指针)和操作(是否有权限)进行合法性判定）
// （3）让进程管理与内存管理，进行一定程度的解耦合
// （进程中会储存有关的内存地址，现在直接储存虚拟地址，物理地址需要的话随便改也影响不到我的进程）
// 
// 肯定还有其他的好处：
// 比如程序创建时虚拟地址先开好，一个物理空间也不开或者开一部分，等需要的时候再开（缺页中断）
