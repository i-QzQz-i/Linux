// 文件是文件属性和文件内容的集合(文件 = 内容 + 属性)
// 
// 文件操作本质上是进程对文件的操作，对文件的操作就是对文件内容、属性做操作
// 编程写入文件时，特指字符串，不要带'\0'，是乱码
// 
// 文本写入 vs 二进制写入
// 系统并不关心写入方式类型，你给什么类型它就写入什么类型
// 所以想要怎么写入自己格式化
// 
// 
// 为什么写代码不直接用系统调用
// 各个语言封装系统调用，来提供自己的库函数接口，是为了代码的可移植性
// 在不同的操作系统，就调用不同的库就行了
// 
// 
//	文件描述符：
// 其实就是数组下标，PCB(task_struct)中维护的一张文件描述符表(files_struct)(指针数组)，表中成员指向被打开的文件(file)
// 所以拿到文件描述符，就能找到对应的文件
// 进程 : 打开的文件 = 1 : n  那么怎么多进程，如何关闭文件 -> 引用计数
// 
// c程序默认会打开三个流输入输出流(文件) --- stdin/stdout/stderr
// extern FILE *stdin;      0(对应的文件描述符)
// extern FILE *stdout;     1
// extern FILE *stderr;     2
// （标准输出和标准错误底层都指向显示器文件，但是在重定向中二者是分离的）
// （分别我们生成日志）
// 
// 文件描述符的分配规则：
// 找到当前没被使用且最小的下标，作为新的文件描述符
//
// 
//	重定向（系统调用dup2(old fp, new fp)）
// 常见重定向：< (输出重定向)、> (输入重定向)、>> (追加重定向)
// 输出/追加重定向：把程序执行的结果从原来的显示器文件，改为输出/追加到自己指定的文件
// 输入重定向：把原本从键盘文件中读取数据改为对指定文件中读取
// dup2底层就是通过文件描述符找到对应文件指针，进行'新''旧'覆盖
// 本质：打开文件的方式 + dup2
// 
// 如何操作
// （1）./a.out > log.txt（默认是重定向标准输出）
// （2）./a.out 1 > log.txt（可以指定重定向到哪）
// （2）./a.out 1 > log.txt 2 > &1（可以将标准输出和标准错误打印到同一文件）
// 
// 
//	理解一切皆文件
// 用结构体描述外设(硬件)，并用指针链接，就把操作系统对设备的管理变为对链表资源的增删查改
// 
// Linux一切皆文件的内核模型：
// 进程->文件描述符->struct file->struct device(设备抽象)->硬件
//                        ↑
// （类似c++中的基类，表层的接口都一样，而下一层通过结构体封装不同函数指针，屏蔽了底层硬件的差异，
// 就是c语言实现的多态，同一调用不同实现）
// 
// 任何计算机问题都可以通过增加一层软件层来解决
// 
// 所以到底什么是一切皆文件？
// 你想啊，你在操作系统中对真正的文件和硬件都是同一套操作(同一API接口)
// 所以一切皆文件就是，内核提供一套统一的API接口，让我们可调取(绝大部分)系统资源（在操作系统看来都在对文件操作）
// 
//	什么是缓冲区(就是内存中的一段空间)
// 作用：减少系统调用(系统调用要付出代价)，提高效率(本质是提高拷贝的效率)
// 
// 如何运行的：（这里是输出缓冲区，当然还有输入缓冲区）
// 我们写入数据->c标准库提供(语言/用户级)的缓冲区->操作系统的缓冲区（包含文件缓冲区）                         
// 那么什么时候c缓冲区刷新到系统：
// 1.强制刷新（fflush） a.立刻刷新 -- 边写边刷新(无缓冲) -- 写透模式 WT
// 2.满足刷新条件 ->  { b.满了 -- 全缓冲 -- 效率最高（一般普通文件采用的方式）
// 3.程序退出           c.行刷新 - 行缓冲 -- 显示器用（符合人们的阅读习惯）
// 系统缓冲区也会使用上述刷新方式，当然还有更加复杂的方式
// 
// c中的FILE就是一个包含int fd 与 缓冲区的结构体
// 
// 如何读+修改文件？
// 把文件从磁盘中读(加载)到文件缓冲区中(拷贝)，再从缓冲区中读到内存(还是拷贝)，内存中修改后->缓冲区->磁盘
// 计算机数据流动的本质：一切皆拷贝
