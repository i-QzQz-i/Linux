#define _CRT_SECURE_NO_WARNINGS 


// 
//		一、进程创建
// 使用fork函数来创建子进程
// 不确定哪个进程先跑完，但是如果使用wait()/waitpid()，
// 父进程就要先跑完来阻塞等待子进程
// fork()的返回值：
// 父：子进程的pid
// 子：0
// 创建失败：-1
// 
// 还有一个vfork函数
// vfork():
// 表层让子进程先跑，内层子进程与父进程共用一套空间，不会发生写时拷贝
// 子进程运行结束需要exit()/_exit()/exec函数
// 
//		二、进程终止
// 进程终止的三种情况（main函数的返回值，表面程序的执行情况，也就是进程退出码）：
// 1.代码运行完毕，结果正确 --- 返回0
// 2.代码运行完毕，结果错误 --- 返回!0（不同的值代表不同的出错原因）
// 3.代码异常终止 --- 返回值不重要
// 
// 常见的进程退出方法：（可通过echo $?来查看最后一个执行的进程的退出码）
// 1.main函数结束（其他函数结束，只代表该函数调用完成）
// 2.任何地方调用exit(status)/_exit(status)进程直接结束
// 3.异常退出: ctrl + c，信号终止
// 
// exit(C)与_exit(系统)
// 二者是上下层的关系，exit的执行流程可看做：
// 执行exit() -> 执行用户的清理函数 -> 刷新缓存区，关闭流等 -> 调用_exit() -> 程序退出
// 所以也可以得到缓存区一定不在操作系统内部，而是由c语言提供的库缓存区
// 
// 
//		三、进程等待
// 进程等待的必要性:
// 1.防止内存泄漏
// 2.看子进程执行得如何
// 
// 所以父进程通过进程等待的方式，回收子进程资源（最重要），获取子进程退出信息（获取退出码）（可选）
// 
// 如何进行等待：
// wait();（阻塞等待）
// waitpid();（非阻塞等待）
// 
// 阻塞等待与非阻塞等待
// 阻塞等待：什么都不做就在那里等
// 非阻塞等待：等待的同时还做自己的事情
// 
// 
//		四、进程替换
// 效果
// 通过特定接口，把你正在运行的程序替换为另一个程序
// 进程 = PCB（内核数据结构） + 代码和数据
// 
// 原理
// 替换过程只是把进程当前的代码和数据覆盖式的替换为新程序，也就是说并没有创建新进程
// 替换成功后就直接执行新代码
// 
// 接口
// 替换函数(exec函数)（执行后不返回）
// 共有六种
// int execl("地址", "该地址下执行的程序", "选项a", "选项b", ......);
// int execlp("该地址下执行的程序", "选项a", "选项b", ......);
// int execle();
// int execv("地址", "该地址下执行的程序", "储存各个选项的数组");
// int execvp("该地址下执行的程序", "储存各个选项的数组");
// int execve();
// 
// l：代表指令选项以list的方式(直接跟在函数后)传递
// v：代表指令选项以vector的方式(跟一个string数组)传递
// p：代表环境变量PATH，可以省略地址
// e：代表环境变量表，可以传一个新的环境变量表（如果不传就继承父进程的表）
